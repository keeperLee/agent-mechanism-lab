/**
 * 【一个必须说清的概念】
 * 标称窗口不是可用空间。窗口再大，模型对中段内容的注意力也会衰减，
 * 这就是常说的「有效上下文远小于标称窗口」。所以填满窗口不是目标 ——
 * 真正该做的是把最关键的事实放在两端，并尽量压缩无关内容。
 * 这个实验室只计算「占了多少」，无法量化「注意力衰减了多少」，
 * 因为那取决于具体模型，没有通用公式。
 */
export const EFFECTIVE_CONTEXT_NOTE =
  '注意：这里算出来的是「占了多少窗口」，不是「模型能用到多少」。'
